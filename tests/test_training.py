@pytest.mark.parametrize(
    ("answer", "problem"),
    [
        ("Con gusto le ayudo. ¿Qué necesita?", None),
        ("Claro, te ayudo con eso.", "tutea"),
        ("¿Quieres que te cuente algo?", "tutea"),
        ("La capital es París [1].", "cita"),
        ("¡Claro! 😊 Le ayudo.", "emojis"),
        ("Opciones:\n1. Uno\n2. Dos\n3. Tres\n4. Cuatro", "lista"),
        ("<think>hmm</think> Hola.", "razonamiento"),
    ],
)
def test_revisa_el_estilo_de_jarvis(answer: str, problem: str | None):
    report = check(answer)
    if problem is None:
        assert report.ok, report.problems
    else:
        assert any(problem in p for p in report.problems), report.problems


