@pytest.mark.db
async def test_exporta_jsonl_y_no_saca_datos_personales_a_la_nube(session_factory, tmp_path):
    service = DatasetService(session_factory)
    added = await service.add(
        "estilo",
        "público",
        personal=False,
        examples=[Example("Hola", "Buenas tardes. ¿En qué le ayudo?")] * 2,  # repetido
    )
    assert added == 1
    await service.add(
        "correcciones", "del dueño", personal=True, examples=[Example("¿Mi perro?", "Rocky.")]
    )
    summary = {d.name: (d.personal, d.examples) for d in await service.overview()}
    assert summary == {"estilo": (False, 1), "correcciones": (True, 1)}

    out = tmp_path / "estilo.jsonl"
    assert await service.export_jsonl(["estilo"], out, "nube", system="SISTEMA") == 1
    record = json.loads(out.read_text(encoding="utf-8"))
    assert [m["role"] for m in record["messages"]] == ["system", "user", "assistant"]
    assert record["messages"][2]["content"] == "Buenas tardes. ¿En qué le ayudo?"

    with pytest.raises(PrivacyError):  # las correcciones personales nunca van a Colab
        await service.export_jsonl(["estilo", "correcciones"], tmp_path / "x.jsonl", "nube")
    local = tmp_path / "local.jsonl"
    assert await service.export_jsonl(["estilo", "correcciones"], local, "local", system="S") == 2
    with pytest.raises(LookupError):
        await service.export_jsonl(["no-existe"], tmp_path / "y.jsonl", "local")


# ---------- Versiones del modelo ----------

OLLAMA_SHOW = '''# Modelfile generated by "ollama show"
FROM C:\\blobs\\sha256-abc
TEMPLATE """{{- if .System }}<|im_start|>system
{{ .System }}<|im_end|>{{ end }}"""
PARAMETER stop <|im_start|>
PARAMETER stop <|im_end|>
PARAMETER temperature 0.7
'''


def test_el_modelfile_nuevo_conserva_la_personalidad(tmp_path):
    chat = chat_format(OLLAMA_SHOW)
    assert chat.startswith('TEMPLATE """') and "PARAMETER stop <|im_end|>" in chat
    assert "temperature 0.7" not in chat  # los parámetros son los de JARVIS, no los del base
    gguf = tmp_path / "jarvis-v1.Q4_K_M.gguf"
    text = modelfile_for(gguf, chat)
    assert text.count("\nFROM ") == 1 and gguf.resolve().as_posix() in text
    assert 'SYSTEM """Eres JARVIS' in text and "PARAMETER num_ctx 6144" in text
    with pytest.raises(ModelError):
        chat_format("FROM x")


@pytest.mark.db
async def test_importar_activar_y_volver(session_factory, session: AsyncSession, tmp_path):
    session.add(ModelVersion(ollama_tag="jarvis:base", base_model="Qwen3", kind="base"))
    await session.commit()
    commands: list[list[str]] = []

    def runner(args):
        commands.append(list(args))
        return OLLAMA_SHOW if args[1] == "show" else "success"

    manager = ModelManager(session_factory, runner=runner)
    await manager.activate("jarvis:base")
    gguf = tmp_path / "jarvis-v1.Q4_K_M.gguf"
    gguf.write_bytes(b"GGUF")
    version = await manager.import_gguf(
        gguf, "jarvis:v1", base_model="Qwen3", template_from="qwen3:4b-instruct"
    )
    assert version.kind == "lora" and version.quantization == "Q4_K_M"
    assert commands[-1][:3] == ["ollama", "create", "jarvis:v1"]

    settings = Settings()
    assert await get_active_model(settings, session_factory) == "jarvis:base"
    await manager.activate("jarvis:v1")
    assert await get_active_model(settings, session_factory) == "jarvis:v1"  # sin reiniciar
    assert await manager.rollback() == "jarvis:base"
    assert await get_active_model(settings, session_factory) == "jarvis:base"

    with pytest.raises(ModelError):
        await manager.activate("no:existe")
    with pytest.raises(ModelError):
        await manager.import_gguf(
            Path("no-existe.gguf"), "x:y", base_model="Q", template_from="qwen3:4b-instruct"
        )


